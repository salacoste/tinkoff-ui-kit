/* --- Motion: sample a css cubic-bezier into SVG polyline points --- */

/** Uniformly-x-sampled points of a cubic-bezier(…) string (structure, no values). */
function bezierSamples(spec: string): Array<[number, number]> {
  const m = /cubic-bezier\(([-\d.]+),([-\d.]+),([-\d.]+),([-\d.]+)\)/.exec(spec);
  if (!m) return [];
  const [x1, y1, x2, y2] = m.slice(1).map(Number);
  const bx = (t: number): number => 3 * (1 - t) ** 2 * t * x1 + 3 * (1 - t) * t ** 2 * x2 + t ** 3;
  const by = (t: number): number => 3 * (1 - t) ** 2 * t * y1 + 3 * (1 - t) * t ** 2 * y2 + t ** 3;
  const points: Array<[number, number]> = [];
  for (let i = 0; i <= 20; i += 1) {
    const x = i / 20;
    // x(t) is monotonic for these curves — bisect for the param at x.
    let lo = 0;
    let hi = 1;
    for (let k = 0; k < 32; k += 1) {
      const mid = (lo + hi) / 2;
      if (bx(mid) < x) lo = mid;
      else hi = mid;
    }
    const t = (lo + hi) / 2;
    points.push([x, by(t)]);
  }
  return points;
}

/** Static SVG preview of a curve token — no animation (baseline-deterministic). */
function curveSvg(spec: string): TemplateResult {
  // Overshoot curves (y outside 0..1) fit the padded box: [-0.3, 1.3] → 5..125.
  const px = (p: [number, number]): string =>
    `${(p[0] * 100).toFixed(1)},${(125 - ((p[1] + 0.3) / 1.6) * 120).toFixed(1)}`;
  const points = bezierSamples(spec).map(px).join(' ');
  return html`
    <svg
      class="tjtr-curve"
      viewBox="0 0 100 130"
      preserveAspectRatio="none"
      aria-hidden="true"
      focusable="false"
    >
      <line x1="0" y1="102.5" x2="100" y2="102.5" style="stroke: var(--tj-color-divider)" />
      <line x1="0" y1="27.5" x2="100" y2="27.5" style="stroke: var(--tj-color-divider)" />
      <polyline
        points="${points}"
        fill="none"
        style="stroke: var(--tj-color-link); stroke-width: 3"
      />
    </svg>
  `;
}

