/** Render a markdown cell's `code` spans as <code> and **bold** as <strong>
 * (the TOKENS.md notes carry both; code wins — bold markers inside a code
 * span are code characters, not markup). */
function mdInline(cell: string): TemplateResult {
  const renderText = (text: string): TemplateResult =>
    html`${text
      .split('**')
      .map((part, index) => (index % 2 === 1 ? html`<strong>${part}</strong>` : part))}`;
  const parts = cell.split('`');
  return html`${parts.map((part, index) => (index % 2 === 1 ? html`<code>${part}</code>` : renderText(part)))}`;
}

