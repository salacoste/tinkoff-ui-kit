/* --- Derivation helpers: STRUCTURE only — every VALUE comes from the maps --- */

/** The dark-layer override of a token, or null when it is theme-invariant. */
function darkValueOf(name: string): string | null {
  return Object.prototype.hasOwnProperty.call(darkColorTokens, name)
    ? darkColorTokens[name as keyof typeof darkColorTokens]
    : null;
}

/**
 * Tokens that may NOT paint a live specimen: invariant (no dark override)
 * AND outside the sweep-legal purple/gold families. Structure — a name set,
 * never a value. chip-ink is listed separately (it renders on the purple
 * ground specimen above).
 */
const UNPAINTABLE_INVARIANTS: readonly string[] = [
  '--tj-color-ink-200',
  '--tj-color-ink-reference-time',
];

/** One table row for a color token: light/dark text values + live specimen. */
function colorRow([name, light]: [string, string]): TemplateResult {
  const dark = darkValueOf(name);
  const unpaintable = UNPAINTABLE_INVARIANTS.includes(name);
  return html`
    <tr>
      <td><code>${name}</code></td>
      <td><code>${light}</code></td>
      <td>
        ${dark
          ? html`<code>${dark}</code>`
          : html`<span class="tjtr-invariant">инвариантно</span>`}
      </td>
      <td>
        ${name === '--tj-color-chip-ink'
          ? html`<span class="tjtr-swatch tjtr-swatch--chip">Aa</span>`
          : unpaintable
            ? html`<span class="tjtr-invariant">нет поверхностей</span>`
            : html`<span class="tjtr-swatch" style="background: var(${name})"></span>`}
      </td>
    </tr>
  `;
}

