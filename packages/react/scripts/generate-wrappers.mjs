// React wrapper generator (spec 1.7 / AD-1).
//
// Reads the committed Custom Elements Manifest of @tk-kit/components and
// writes one `@lit/react` createComponent wrapper per custom-element
// definition into src/generated/. Deterministic: same manifest in, same
// bytes out (sorted by tag name, no timestamps) — that is what makes the
// root `check:gen` drift gate (`pnpm gen && git diff --exit-code`) sound.
//
// No behavior, styling, or a11y logic EVER lives here or in the generated
// files (AD-1): the wrapper only binds tagName + elementClass + the owned
// event registry (src/event-map.ts). Wrappers import elements from the
// package root `@tk-kit/components` — the same public entry consumers use.
//
// Run via `pnpm --filter @tk-kit/react gen:wrappers` (root: `pnpm gen`).
import { readFileSync, readdirSync, rmSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(SCRIPT_DIR, '..', '..');
const MANIFEST_PATH = join(REPO_ROOT, 'components', 'custom-elements.json');
const GENERATED_DIR = join(SCRIPT_DIR, '..', 'src', 'generated');

/** 'tk-segmented-radio' → 'SegmentedRadio' (wrapper component name). */
const wrapperName = (tag) => {
  const body = tag.replace(/^tk-/, '');
  return body
    .split('-')
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join('');
};

/** 'tk-segmented-radio' → 'segmented-radio' (generated file stem). */
const fileStem = (tag) => tag.replace(/^tk-/, '');

/** Collect { tag, className } pairs from every custom-element-definition export. */
function readElements(manifest) {
  const elements = [];
  for (const module of manifest.modules ?? []) {
    for (const exportEntry of module.exports ?? []) {
      if (exportEntry.kind !== 'custom-element-definition') continue;
      const className = exportEntry.declaration?.name;
      if (!className || typeof exportEntry.name !== 'string') {
        throw new Error(
          `generate-wrappers: custom-element-definition without a resolvable class name in ${module.path} — re-run pnpm --filter @tk-kit/components gen:manifest`,
        );
      }
      elements.push({ tag: exportEntry.name, className });
    }
  }
  if (elements.length === 0) {
    throw new Error(
      `generate-wrappers: no custom-element definitions found in ${MANIFEST_PATH} — the manifest must list at least one element (run pnpm --filter @tk-kit/components gen:manifest)`,
    );
  }
  return elements.sort((a, b) => a.tag.localeCompare(b.tag));
}

let manifest;
try {
  manifest = JSON.parse(readFileSync(MANIFEST_PATH, 'utf8'));
} catch (error) {
  throw new Error(
    `generate-wrappers: cannot read the Custom Elements Manifest at ${MANIFEST_PATH}: ${error.message}. Generate it first: pnpm --filter @tk-kit/components gen:manifest (or pnpm gen at the root).`,
  );
}

const elements = readElements(manifest);

// Clean rebuild: a removed element's wrapper must not linger as a stale
// hand-edit — orphaned generated files are deleted with the rest.
mkdirSync(GENERATED_DIR, { recursive: true });
for (const entry of readdirSync(GENERATED_DIR)) {
  if (entry.endsWith('.ts') || entry.endsWith('.tsx')) {
    rmSync(join(GENERATED_DIR, entry));
  }
}

for (const { tag, className } of elements) {
  const name = wrapperName(tag);
  const content = `// AUTO-GENERATED by packages/react/scripts/generate-wrappers.mjs — DO NOT EDIT.
// Source: @tk-kit/components custom-elements.json (${tag}). Regenerate: pnpm gen.
import * as React from 'react';
import { createComponent } from '@lit/react';

import { ${className} } from '@tk-kit/components';
import { EVENT_MAP } from '../event-map.js';

export const ${name} = createComponent({
  displayName: '${name}',
  tagName: '${tag}',
  elementClass: ${className},
  react: React,
  events: EVENT_MAP['${tag}'] ?? {},
});
`;
  writeFileSync(join(GENERATED_DIR, `${fileStem(tag)}.ts`), content);
  console.log(`generate-wrappers: src/generated/${fileStem(tag)}.ts (${tag} → ${name})`);
}

// Barrels keep a stable 1:1 order with the generated files.
const indexContent = `// AUTO-GENERATED by packages/react/scripts/generate-wrappers.mjs — DO NOT EDIT.
${elements.map(({ tag }) => `export * from './${fileStem(tag)}.js';`).join('\n')}
`;
writeFileSync(join(GENERATED_DIR, 'index.ts'), indexContent);
console.log(`generate-wrappers: src/generated/index.ts (${elements.length} wrapper${elements.length === 1 ? '' : 's'})`);
